/** Rewrite one `yarn.lock` entry block in place, addressed by a predicate over
 * its text. Keeps the surrounding bytes verbatim so a strict round-trip still
 * compares against producer output. */
function editBerryEntry(
  text: string,
  matches: (block: string) => boolean,
  edit: (lines: readonly string[]) => string[],
): string {
  const blocks = text.split('\n\n')
  const index = blocks.findIndex(block => block.startsWith('"') && matches(block))
  expect(index).toBeGreaterThanOrEqual(0)
  const next = blocks.slice()
  next[index] = edit(blocks[index]!.split('\n')).join('\n')
  return next.join('\n\n')
}

